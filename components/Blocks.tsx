"use client";
import { useState } from "react";
import type { Artifact, Block } from "@/lib/types";

function Draft({ label, text }: { label: string; text: string }) {
  const [copied, setCopied] = useState(false);
  return (
    <div className="draft">
      <div className="row" style={{ justifyContent: "space-between" }}>
        <b>{label}</b>
        <span className="row">
          <span className="tag">draft — not sent</span>
          <button className="ghost" onClick={() => navigator.clipboard.writeText(text).then(() => setCopied(true))}>
            {copied ? "Copied" : "Copy"}
          </button>
        </span>
      </div>
      <pre>{text}</pre>
    </div>
  );
}

function One({ b }: { b: Block }) {
  switch (b.t) {
    case "h":
      return <h2>{b.text}</h2>;
    case "p":
      return <p>{b.text}</p>;
    case "note":
      return <div className="note">{b.text}</div>;
    case "list":
      return (
        <ul>
          {b.items.map((it, i) => (
            <li key={i}>
              {it.tag && <span className="tag">{it.tag}</span>} {it.text}{" "}
              {it.url && (
                <a href={it.url} target="_blank" rel="noreferrer">
                  source
                </a>
              )}
            </li>
          ))}
        </ul>
      );
    case "table":
      return (
        <div className="tablewrap">
          <table>
            <thead>
              <tr>{b.cols.map((c) => <th key={c}>{c}</th>)}</tr>
            </thead>
            <tbody>
              {b.rows.map((r, i) => (
                <tr key={i}>{r.map((c, j) => <td key={j}>{c}</td>)}</tr>
              ))}
            </tbody>
          </table>
        </div>
      );
    case "draft":
      return <Draft label={b.label} text={b.text} />;
    case "score":
      return (
        <div className="card">
          <div className="row" style={{ justifyContent: "space-between" }}>
            <b>{b.label}</b>
            <b>
              {b.value}/{b.max}
            </b>
          </div>
          <div className="bar">
            <i style={{ width: `${Math.min(100, (b.value / b.max) * 100)}%` }} />
          </div>
          {b.why && <p className="muted">{b.why}</p>}
        </div>
      );
    case "svg":
      // SVG is generated by lib/svg.ts with every text value escaped
      return <div className="svgwrap" dangerouslySetInnerHTML={{ __html: b.svg }} />;
    case "postcard":
      return (
        <>
          <div className="postcard">
            <div className="front">{b.front}</div>
            <div className="back">{b.back}</div>
          </div>
          <button className="ghost noprint" onClick={() => window.print()}>
            Print / save as PDF
          </button>
        </>
      );
    case "sources":
      return (
        <details className="card">
          <summary>Sources ({b.items.length})</summary>
          <ol>
            {b.items.map((s, i) => (
              <li key={i}>
                <a href={s.url} target="_blank" rel="noreferrer">
                  {s.title || s.url}
                </a>
              </li>
            ))}
          </ol>
        </details>
      );
  }
}

export function Blocks({ artifact }: { artifact: Artifact }) {
  return (
    <section>
      <h1 style={{ fontSize: 24 }}>{artifact.title}</h1>
      {artifact.blocks.map((b, i) => (
        <One key={i} b={b} />
      ))}
    </section>
  );
}
